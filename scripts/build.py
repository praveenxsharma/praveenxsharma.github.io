def strip_md(text: str) -> str:
    text = re.sub(r"```.*?```", " ", text, flags=re.S)
    text = re.sub(r"!\[\[[^\]]*\]\]", " ", text)
    text = re.sub(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]", lambda m: m.group(2) or m.group(1), text)
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", " ", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"^[#>\-*+\s]+", "", text, flags=re.M)
    return re.sub(r"[`*_=~]", "", text).strip()


def to_date(value, fallback: date) -> date:
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    try:
        return date.fromisoformat(str(value).strip()[:10])
    except ValueError:
        return fallback


def norm_tags(value) -> list[str]:
    if not value:
        return ["misc"]
    if isinstance(value, str):
        value = re.split(r"[,\s]+", value)
    tags = [str(t).strip(' []"\'#').lower() for t in value]
    return [t for t in tags if t] or ["misc"]


def git_date(path: Path) -> date | None:
    """Last commit date, so undated posts don't reorder on every CI checkout."""
    import subprocess

    try:
        out = subprocess.run(
            ["git", "log", "-1", "--format=%cs", "--", str(path.relative_to(ROOT))],
            cwd=ROOT, capture_output=True, text=True, timeout=10,
        ).stdout.strip()
        return date.fromisoformat(out) if out else None
    except (OSError, ValueError, subprocess.SubprocessError):
        return None


def parse(path: Path) -> dict:
    raw = path.read_text(encoding="utf-8")
    front, body = "", raw
    if raw.startswith("---") and len(raw.split("---", 2)) == 3:
        _, front, body = raw.split("---", 2)
    meta = (yaml.safe_load(front) or {}) if front.strip() else {}
    if not isinstance(meta, dict):
        meta = {}

    fallback_date = git_date(path) or date.fromtimestamp(path.stat().st_mtime)
    meta["date"] = to_date(
        meta.get("date") or meta.get("created") or meta.get("date created"),
        fallback_date,
    )
    meta["title"] = str(meta.get("title") or path.stem.replace("-", " ").replace("_", " ")).strip()
    meta["tags"] = norm_tags(meta.get("tags"))
    meta["slug"] = re.sub(r"[^a-z0-9]+", "-", str(meta.get("slug") or path.stem).lower()).strip("-")
    meta["body"] = body.strip()

    summary = strip_md(str(meta.get("summary") or ""))
    if not summary:
        paragraphs = [p for p in re.split(r"\n\s*\n", meta["body"]) if not p.lstrip().startswith("#")]
        summary = strip_md(paragraphs[0]) if paragraphs else meta["title"]
    if len(summary) > 180:
        summary = summary[:177].rsplit(" ", 1)[0] + "..."
    meta["summary"] = summary or meta["title"]

    meta["source"] = path
    return meta


def obsidian_to_md(text: str, slugs: dict[str, str]) -> str:
    """Convert Obsidian-only syntax to standard markdown."""
    text = re.sub(r"%%.*?%%", "", text, flags=re.S)
    text = re.sub(r"==(.+?)==", r"<mark>\1</mark>", text)
    text = re.sub(r"!\[\[([^\]|]+)(?:\|[^\]]*)?\]\]", lambda m: f"![{m.group(1)}]({m.group(1).strip()})", text)

    def link(m):
        target, label = m.group(1).strip(), m.group(2)
        label = label or target
        slug = re.sub(r"[^a-z0-9]+", "-", target.lower()).strip("-")
        return f"[{label}](../{slug}/)" if slug in slugs else label

    return re.sub(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]", link, text)


def render(meta: dict, slugs: dict[str, str]) -> str:
    text = markdown.markdown(
        obsidian_to_md(meta["body"], slugs),
        extensions=["fenced_code", "tables", "attr_list", "toc", "sane_lists"],
    )
    # hljs-init.js reads data-filename off <pre>; markdown puts it on <code>.
    text = re.sub(
        r'<pre><code class="language-([^"]+)" data-filename="([^"]+)">',
        r'<pre data-filename="\2"><code class="language-\1">',
        text,
    )
    return text


def words_of(meta: dict) -> int:
    plain = re.sub(r"```.*?```", "", meta["body"], flags=re.S)
    return len(re.findall(r"\w+", plain))


def post(meta: dict, year: int, slugs: dict[str, str]) -> str:
    words = words_of(meta)
    tags = meta.get("tags") or ["misc"]
    url = f"{SITE}/blog/{meta['slug']}/"
    jsonld = json.dumps({
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        "headline": meta["title"],
        "description": meta["summary"],
        "datePublished": meta["date"].isoformat(),
        "dateModified": meta["date"].isoformat(),
        "url": url,
        "mainEntityOfPage": {"@type": "WebPage", "@id": url},
        "image": OG_IMAGE,
        "keywords": ", ".join(tags),
        "author": {"@type": "Person", "name": AUTHOR, "url": SITE + "/", "sameAs": SAME_AS},
        "publisher": {"@type": "Person", "name": AUTHOR, "url": SITE + "/"},
    }, ensure_ascii=False)
    return PAGE.substitute(
        slug=meta["slug"],
        title=html.escape(meta["title"]),
        summary=html.escape(meta["summary"]),
        url=url,
        iso_date=meta["date"].isoformat(),
        og_image=OG_IMAGE,
        author=AUTHOR,
        jsonld=jsonld,
        date=meta["date"].strftime("%d/%m/%y"),
        words=f"{words:,}",
        read=max(1, round(words / 200)),
        tags="\n".join(
            f'        <span class="tag-pill {TAG_CLASS.get(t, "tag-misc")}">{html.escape(t)}</span>'
            for t in tags
        ),
        body=render(meta, slugs),
        year=year,
    )


def card(meta: dict) -> str:
    words = words_of(meta)
    tags = meta.get("tags") or ["misc"]
    first = tags[0]
    return CARD.substitute(
        slug=meta["slug"],
        date=meta["date"].isoformat(),
        tag_class=TAG_CLASS.get(first, "tag-misc"),
        tag_label=html.escape(first),
        title=html.escape(meta["title"]),
        summary=html.escape(meta["summary"]),
        words=f"{words:,}",
        read=max(1, round(words / 200)),
    )


def build() -> int:
    import shutil

    posts = [parse(p) for p in sorted(SRC.glob("*.md"))]
    posts = [p for p in posts if not p.get("draft")]
    posts.sort(key=lambda p: p["date"], reverse=True)
    year = max(p["date"].year for p in posts) if posts else date.today().year
    slugs = {p["slug"]: p["slug"] for p in posts}

    for meta in posts:
        out = BLOG / meta["slug"] / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(post(meta, year, slugs), encoding="utf-8")
        print(f"  blog/{meta['slug']}/index.html")

        # Keep local images next to the .md working: copy what the post references.
        for name in set(re.findall(r"!\[[^\]]*\]\(([^)\s]+)", meta["body"])) | set(
            re.findall(r"!\[\[([^\]|]+)", meta["body"])
        ):
            src = SRC / name
            if src.is_file():
                shutil.copy2(src, out.parent / name)
                print(f"    + {name}")

    # Drop pages left behind when a post is renamed or deleted.
    for stale in BLOG.iterdir():
        page = stale / "index.html"
        if stale.is_dir() and stale.name not in slugs and page.is_file():
            if "generated by scripts/build.py" in page.read_text(encoding="utf-8"):
                shutil.rmtree(stale)
                print(f"  - blog/{stale.name}/ (stale)")

    index = INDEX.read_text(encoding="utf-8")
    if START not in index or END not in index:
        raise SystemExit(f"blog/index.html: missing {START} / {END} markers")
    head, rest = index.split(START, 1)
    _, tail = rest.split(END, 1)
    cards = "\n\n".join(card(p) for p in posts)
    INDEX.write_text(f"{head}{START}\n\n{cards}\n\n    {END}{tail}", encoding="utf-8")
    print(f"  blog/index.html ({len(posts)} cards)")

    lastmod = posts[0]["date"].isoformat() if posts else date.today().isoformat()
    urls = [(SITE + "/", lastmod), (SITE + "/blog/", lastmod)]
    urls += [(f"{SITE}/blog/{p['slug']}/", p["date"].isoformat()) for p in posts]
    entries = "\n".join(
        f"  <url>\n    <loc>{u}</loc>\n    <lastmod>{d}</lastmod>\n  </url>" for u, d in urls
    )
    (ROOT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{entries}\n</urlset>\n",
        encoding="utf-8",
    )
    print(f"  sitemap.xml ({len(urls)} urls)")
    return 0


def check() -> int:
    meta = {
        "title": "T & <x>", "date": date(2026, 1, 2),
        "summary": "s", "tags": ["android"], "slug": "s", "body": "# Head\n\n```python\nprint(1)\n```",
    }
    slugs = {"s": "s"}
    out = post(meta, 2026, slugs)
    assert "T &amp; &lt;x&gt;" in out, "title not escaped"
    assert 'id="head"' in out, "toc ids missing"
    assert 'class="language-python"' in out, "fenced code broken"
    assert "tag-android" in out, "tag class broken"
    assert 'href="../../blog/"' in out, "asset/back-link paths broken"
    assert "02/01/26" in out, "date format broken"
    assert card(meta).count('href="s/"') == 1, "card slug broken"
    assert 'rel="canonical" href="https://praveenxsharma.github.io/blog/s/"' in out, "canonical missing"
    assert '"@type": "BlogPosting"' in out, "json-ld missing"
    assert "<time datetime=\"2026-01-02\">" in out, "time element missing"
    assert 'property="og:image"' in out, "og image missing"

    # Obsidian syntax conversion
    assert obsidian_to_md("![[shot.png]]", slugs) == "![shot.png](shot.png)", "embed broken"
    assert obsidian_to_md("see [[Other Note]]", {"other-note": "x"}) == "see [Other Note](../other-note/)", "wikilink broken"
    assert obsidian_to_md("see [[Other Note]]", {}) == "see Other Note", "dangling wikilink broken"
    assert "<mark>hi</mark>" in obsidian_to_md("==hi==", slugs), "highlight broken"

    # Frontmatter fallbacks
    assert to_date("2026-05-27", date(2000, 1, 1)) == date(2026, 5, 27)
    assert to_date("garbage", date(2000, 1, 1)) == date(2000, 1, 1)
    assert norm_tags("security, #linux") == ["security", "linux"]
    assert norm_tags('"[misc]"') == ["misc"], "quoted bracket tag leaks"
    assert norm_tags("[misc]") == ["misc"]
    assert norm_tags("") == ["misc"]
    print("self-check ok")
    return 0


if __name__ == "__main__":
    sys.exit(check() if "--check" in sys.argv else build())
